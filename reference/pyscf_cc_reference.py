#!/usr/bin/env python3
"""Independent CCSD and CCSD(T) reference energies for ΨLab 3.1, computed with PySCF.

Same molecules, geometries, basis files and linear-dependency threshold as
reference/pyscf_rhf_reference.py; all electrons are correlated (no frozen core). PySCF's
closed-shell RCCSD and its (T) correction (ccsd_t.kernel) on the canonical RHF orbitals.
CCSDT and CCSDTQ are not in PySCF; ΨLab checks them against brute-force coupled cluster
(backend/tests/gen_cc_reference.py) and against Full CI where they are exact.

Usage:
  python3 reference/pyscf_cc_reference.py          # -> backend/tests/data/cc_molecules_reference.json
"""
import json
import pathlib
import sys
import time

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pyscf_rhf_reference as rr  # noqa: E402  (sets the 1e-7 linear-dependency threshold)
import pyscf  # noqa: E402
from pyscf import cc, gto, scf  # noqa: E402
from pyscf.cc import ccsd_t  # noqa: E402

OUT = rr.ROOT / "backend" / "tests" / "data" / "cc_molecules_reference.json"

CASES = [("H2", "aug-cc-pVDZ"), ("H2", "aug-cc-pVTZ"), ("LiH", "aug-cc-pVDZ"), ("LiH", "aug-cc-pCVDZ"),
         ("H2O", "aug-cc-pVDZ"), ("H2O", "aug-cc-pCVDZ"), ("H2O", "aug-cc-pVTZ")]


def build(name, basis):
    geo = dict(rr.GEOMETRIES[name])
    at = rr.atoms(name, geo["R"], geo.get("angle"))
    bas = {s: rr.element_basis(basis, s)[0] for s, _ in at}
    return geo, gto.M(atom=[[s, xyz] for s, xyz in at], basis=bas, unit="Bohr", cart=False, verbose=0)


def run(name, basis):
    geo, mol = build(name, basis)
    mf = scf.RHF(mol)
    mf.conv_tol = 1e-12
    mf.conv_tol_grad = 1e-8
    mf.direct_scf_tol = 1e-14
    mf.kernel()
    if not mf.converged:
        raise RuntimeError(f"RHF did not converge for {name}/{basis}")
    mc = cc.RCCSD(mf)
    mc.conv_tol = 1e-12
    mc.conv_tol_normt = 1e-9
    mc.max_cycle = 200
    mc.kernel()
    if not mc.converged:
        raise RuntimeError(f"CCSD did not converge for {name}/{basis}")
    et = ccsd_t.kernel(mc, mc.ao2mo(), verbose=0)
    return dict(molecule=name, basis=basis, R_bohr=geo["R"], orbitals=mf.mo_coeff.shape[1],
                rhf_energy=float(mf.e_tot), ccsd_energy=float(mc.e_tot), triples=float(et),
                ccsd_t_energy=float(mc.e_tot + et))


def main():
    results = []
    for name, basis in CASES:
        t0 = time.time()
        r = run(name, basis)
        r["pyscf_seconds"] = round(time.time() - t0, 1)
        results.append(r)
        print(f"{name:4s} {basis:13s} n={r['orbitals']:4d}  CCSD {r['ccsd_energy']:.10f}  (T) {r['triples']:.10f}"
              f"  CCSD(T) {r['ccsd_t_energy']:.10f}", flush=True)
    OUT.write_text(json.dumps({
        "description": "CCSD and CCSD(T) total energies (E_h), all electrons, from PySCF with the basis files in "
                       "basis/; generated by reference/pyscf_cc_reference.py",
        "program": f"PySCF {pyscf.__version__}",
        "cases": results}, indent=1) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
