#!/usr/bin/env python3
"""Independent CCSD, CCSD(T) and Full CI gradients for ΨLab 5.0, computed with PySCF.

Geometries (bohr) and basis files as in reference/pyscf_gradient_reference.py (distorted,
no symmetry for H2O); all electrons correlated, canonical RHF orbitals, overlap eigenvalues
below 1e-7 removed (none are at these geometries).

  CCSD      pyscf.cc.CCSD + pyscf.grad.ccsd   (Lambda equations, relaxed densities, Z-vector)
  CCSD(T)   pyscf.cc.CCSD + pyscf.grad.ccsd_t (CCSD(T) Lagrangian)
  Full CI   pyscf.mcscf.CASCI with every orbital active and every electron + pyscf.grad.casci
            (= Full CI; the orbital response vanishes)

Usage:
  python3 reference/pyscf_correlated_gradient_reference.py           # -> backend/tests/data/correlated_gradient_reference.json
  python3 reference/pyscf_correlated_gradient_reference.py --check   # recompute and compare
"""
import argparse
import json
import pathlib
import sys
import time

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import pyscf_rhf_reference as rr  # noqa: E402  (1e-7 linear-dependency threshold)
import pyscf_gradient_reference as gr  # noqa: E402  (geometries)
import pyscf  # noqa: E402
from pyscf import cc, mcscf, scf  # noqa: E402
from pyscf.grad import ccsd as ccsd_grad  # noqa: E402,F401
from pyscf.grad import ccsd_t as ccsd_t_grad  # noqa: E402

OUT = rr.ROOT / "backend" / "tests" / "data" / "correlated_gradient_reference.json"

CASES = [
    ("H2O-distorted", "aug-cc-pVDZ", "CCSD"),
    ("H2O-distorted", "aug-cc-pVDZ", "CCSD(T)"),
    ("LiH-3.10", "aug-cc-pVDZ", "CCSD"),
    ("LiH-3.10", "aug-cc-pVDZ", "CCSD(T)"),
    ("LiH-3.10", "aug-cc-pVDZ", "FCI"),
    ("H2-1.30", "aug-cc-pVTZ", "CCSD"),
    ("H2-1.30", "aug-cc-pVTZ", "FCI"),
]


def run(geometry, basis, method):
    mol = gr.build(geometry, basis)
    t0 = time.time()
    mf = scf.RHF(mol)
    mf.conv_tol = 1e-12
    mf.conv_tol_grad = 1e-9
    mf.direct_scf_tol = 1e-14
    mf.kernel()
    if not mf.converged:
        raise RuntimeError(f"RHF did not converge for {geometry}/{basis}")
    if method in ("CCSD", "CCSD(T)"):
        mc = cc.CCSD(mf)
        mc.conv_tol = 1e-12
        mc.conv_tol_normt = 1e-10
        mc.max_cycle = 300
        mc.kernel()
        if not mc.converged:
            raise RuntimeError("CCSD did not converge")
        if method == "CCSD":
            mc.solve_lambda()
            g = mc.nuc_grad_method().kernel()
            e = mc.e_tot
        else:
            e = mc.e_tot + mc.ccsd_t()
            g = ccsd_t_grad.Gradients(mc).kernel()
    else:
        mcas = mcscf.CASCI(mf, mol.nao, mol.nelectron)
        mcas.fcisolver.conv_tol = 1e-12
        mcas.fcisolver.max_cycle = 300
        e = mcas.kernel()[0]
        g = mcas.nuc_grad_method().kernel()
    return dict(geometry=geometry, basis=basis, method=method,
                atoms=[[s, list(xyz)] for s, xyz in gr.GEOMETRIES[geometry]],
                nbf=mol.nao, energy=float(e), gradient=[float(v) for v in g.ravel()],
                seconds=round(time.time() - t0, 2))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--tolerance", type=float, default=1e-8)
    args = ap.parse_args()
    stored = json.loads(OUT.read_text()) if OUT.exists() else None
    results, worst = [], 0.0
    for geometry, basis, method in CASES:
        r = run(geometry, basis, method)
        results.append(r)
        line = f"{geometry:14s} {basis:12s} {method:8s} E = {r['energy']:.10f}  ({r['seconds']} s)"
        if args.check and stored:
            ref = next((c for c in stored["cases"]
                        if (c["geometry"], c["basis"], c["method"]) == (geometry, basis, method)), None)
            if ref:
                d = max(abs(a - b) for a, b in zip(ref["gradient"], r["gradient"]))
                d = max(d, abs(ref["energy"] - r["energy"]))
                worst = max(worst, d)
                line += f"  |diff| {d:.1e}"
        print(line, flush=True)
    if args.check:
        print(f"largest difference from the stored values: {worst:.1e}")
        return 0 if worst <= args.tolerance else 1
    doc = {
        "description": "CCSD, CCSD(T) and Full CI (CASCI, all orbitals) energies (E_h) and analytic gradients "
                       "(E_h/bohr) from PySCF; generated by reference/pyscf_correlated_gradient_reference.py",
        "program": f"PySCF {pyscf.__version__}",
        "settings": "all electrons correlated; RHF conv_tol 1e-12; CCSD conv_tol 1e-12, conv_tol_normt 1e-10; "
                    "FCI conv_tol 1e-12",
        "cases": results,
    }
    OUT.write_text(json.dumps(doc, indent=1) + "\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
